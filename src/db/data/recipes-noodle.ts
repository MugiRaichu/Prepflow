/**
 * たんぱく質の多い麺類。
 *
 * **すべてここで書き起こしたもの。**どこかのレシピを取り込んだものではない
 * （[[D-073]] / [[D-105]]）。材料の組み合わせと分量は、食材マスタにある
 * ものだけで、家庭料理の一般的な作り方に沿って組んだ。
 *
 * 分けて置いてある理由は、**麺の日にたんぱく質が落ちていた**から。
 * 麺は8品あったが `高たんぱく` は2品だけで、「麺を3食」を指定すると
 * その週のたんぱく質が目標を割った。麺そのものは 100g あたり 2.6〜14g しかない。
 *
 * なので**麺を主役にしない**。肉・魚・卵・豆腐を先に決めて、麺はその下に敷く。
 * 1人前あたり 30g 前後のたんぱく質を目安にしてある。
 *
 * 作り置きの都合も麺は難しい。ゆでた麺は冷蔵で伸びるので、
 *   - ぶっかけ・つけ系は**具だけ作り置き**して、麺は食べる直前にゆでる
 *   - 炒め麺は当日〜翌日まで
 * を守る。`keepsDays` はその前提で短く取ってある。
 *
 * 栄養値・原価・出来上がり重量はここに書かない。すべて食材マスタから計算する。
 *
 * 分量の目安（食材マスタの単位に合わせてある）:
 *   しょうゆ・みりん・みそ 大さじ1 = 18g / 砂糖 大さじ1 = 9g
 *   油 大さじ1 = 12g・小さじ1 = 4g / 塩 小さじ1 = 6g / 片栗粉 大さじ1 = 8g
 *   マヨネーズ 大さじ1 = 12g / ケチャップ 大さじ1 = 15g / 料理酒 大さじ1 = 15g
 *   鶏がらスープの素 小さじ1 = 3g / オイスターソース 大さじ1 = 18g
 *   すりごま 大さじ1 = 6g / 酢 大さじ1 = 15g / 豆板醤 小さじ1 = 6g
 */
