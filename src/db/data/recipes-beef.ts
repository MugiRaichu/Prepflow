/**
 * 牛肉の主菜。
 *
 * **すべてここで書き起こしたもの。**どこかのレシピを取り込んだものではない
 * （[[D-073]] / [[D-105]]）。材料の組み合わせと分量は、食材マスタにある
 * ものだけで、家庭料理の一般的な作り方に沿って組んだ。
 *
 * 分けて置いてある理由は、**牛肉だけ数が足りていなかった**から。
 * 鶏肉22品・豚肉25品に対して牛肉は5品しかなく、「牛肉を2食」のような
 * 希望を出しても、予算や日持ちで数品落ちた時点で組めなくなっていた。
 *
 * 牛肉は高い（こま切れで100gあたり240円ほど）。
 * 予算の制約で落ちる回数も多くなるので、**安く作れる形も混ぜてある**——
 * 根菜や白菜でかさを増やす煮もの、こま切れを少量だけ使う炒めもの。
 * ステーキのような「肉だけ」の品は入れていない。作り置きに向かない。
 *
 * 栄養値・原価・出来上がり重量はここに書かない。すべて食材マスタから計算する。
 *
 * 分量の目安（食材マスタの単位に合わせてある）:
 *   しょうゆ・みりん・みそ 大さじ1 = 18g / 砂糖 大さじ1 = 9g
 *   油 大さじ1 = 12g・小さじ1 = 4g / 塩 小さじ1 = 6g / 片栗粉 大さじ1 = 8g
 *   ケチャップ 大さじ1 = 15g / 料理酒 大さじ1 = 15g / 小麦粉 大さじ1 = 8g
 *   鶏がらスープの素 小さじ1 = 3g / 顆粒コンソメ 小さじ1 = 3g
 *   オイスターソース 大さじ1 = 18g / すりごま 大さじ1 = 6g
 */
